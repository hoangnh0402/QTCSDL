-- #region pkg_demo_spec
CREATE OR REPLACE PACKAGE pkg_demo AUTHID DEFINER AS
  -- Đưa biểu mẫu 2 về trạng thái 2/3 chỗ, còn hạn đăng ký
  PROCEDURE reset_race;
  -- Xóa phản hồi của một người trên biểu mẫu 1 để thử lại kịch bản nộp trùng
  PROCEDURE reset_duplicate (p_user_id IN NUMBER);
  -- Đưa toàn bộ dữ liệu minh họa về trạng thái ban đầu
  PROCEDURE reset_all;

  -- CÁCH LÀM SAI: đọc số lượng rồi mới ghi, không khóa, không tăng bộ đếm
  PROCEDURE submit_naive (p_form_id IN NUMBER, p_user_id IN NUMBER);

  -- Giả lập "một phiên khác" trong cùng phiên SQL*Plus bằng giao dịch tự trị
  PROCEDURE other_session_submit (p_form_id IN NUMBER, p_user_id IN NUMBER);
  FUNCTION  other_session_lock   (p_form_id IN NUMBER) RETURN VARCHAR2;

  -- Bộ câu trả lời hợp lệ mẫu cho biểu mẫu 1 và 2
  FUNCTION sample_answers (p_form_id IN NUMBER) RETURN CLOB;
END pkg_demo;
/
-- #endregion

-- #region pkg_demo_body
CREATE OR REPLACE PACKAGE BODY pkg_demo AS

  FUNCTION sample_answers (p_form_id IN NUMBER) RETURN CLOB IS
  BEGIN
    RETURN CASE p_form_id
      WHEN 1 THEN '[{"q":1,"n":4},{"q":2,"o":2},{"q":3,"o":6},{"q":3,"o":8},'
               || '{"q":4,"t":"Phiếu minh họa"}]'
      WHEN 2 THEN '[{"q":5,"t":"0901234567"},{"q":6,"o":10},{"q":7,"o":12}]'
      ELSE '[]'
    END;
  END sample_answers;

  PROCEDURE reset_race IS
  BEGIN
    DELETE FROM responses WHERE form_id = 2 AND response_id NOT IN (5, 6);
    UPDATE forms
       SET status = 'OPEN', max_responses = 3, response_count = 2,
           close_at = TRUNC(SYSTIMESTAMP) + INTERVAL '30' DAY
     WHERE form_id = 2;
    COMMIT;
  END reset_race;

  PROCEDURE reset_duplicate (p_user_id IN NUMBER) IS
  BEGIN
    DELETE FROM responses
     WHERE form_id = 1 AND respondent_id = p_user_id
       AND response_id NOT IN (1, 2, 3, 4);
    UPDATE forms f
       SET response_count = (SELECT COUNT(*) FROM responses r
                              WHERE r.form_id = f.form_id)
     WHERE form_id = 1;
    COMMIT;
  END reset_duplicate;

  PROCEDURE reset_all IS
  BEGIN
    reset_race;
    DELETE FROM responses WHERE form_id = 1 AND response_id NOT IN (1, 2, 3, 4);
    UPDATE forms f
       SET response_count = (SELECT COUNT(*) FROM responses r
                              WHERE r.form_id = f.form_id),
           title = CASE form_id
             WHEN 1 THEN 'Lấy ý kiến người học về học phần Quản trị cơ sở dữ liệu nâng cao'
             WHEN 2 THEN 'Đăng ký tham dự hội thảo "Ứng dụng AI trong quản trị dữ liệu"'
             WHEN 3 THEN 'Khảo sát nhu cầu sử dụng phòng tự học'
             WHEN 4 THEN 'Đăng ký đề tài bài tập lớn học kỳ 2'
             ELSE title END
     WHERE form_id IN (1, 2, 3, 4);
    UPDATE forms SET status = 'OPEN',
                     close_at = TIMESTAMP '2026-11-30 23:59:59'
     WHERE form_id = 1;
    COMMIT;
  END reset_all;

  PROCEDURE submit_naive (p_form_id IN NUMBER, p_user_id IN NUMBER) IS
    v_count NUMBER;
    v_max   NUMBER;
  BEGIN
    SELECT max_responses INTO v_max FROM forms WHERE form_id = p_form_id;
    SELECT COUNT(*) INTO v_count FROM responses WHERE form_id = p_form_id;

    IF v_count >= v_max THEN
      RAISE_APPLICATION_ERROR(-20021, 'Biểu mẫu đã đủ chỗ');
    END IF;

    DBMS_SESSION.SLEEP(0.5);     -- thời gian xử lý giữa lúc kiểm tra và lúc ghi

    INSERT INTO responses (form_id, respondent_id)
    VALUES (p_form_id, p_user_id);
    COMMIT;
  END submit_naive;

  PROCEDURE other_session_submit (p_form_id IN NUMBER, p_user_id IN NUMBER) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
    v_id NUMBER;
  BEGIN
    pkg_response.submit(p_form_id, p_user_id, sample_answers(p_form_id),
                        60, '10.10.9.9', 'other-session', v_id, 1);
  END other_session_submit;

  FUNCTION other_session_lock (p_form_id IN NUMBER) RETURN VARCHAR2 IS
    PRAGMA AUTONOMOUS_TRANSACTION;
    v_id NUMBER;
  BEGIN
    SELECT form_id INTO v_id FROM forms
     WHERE form_id = p_form_id
       FOR UPDATE NOWAIT;
    ROLLBACK;
    RETURN 'Phiên khác khóa được dòng biểu mẫu ' || p_form_id;
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK;
      RETURN 'Phiên khác bị từ chối: ' || SQLERRM;
  END other_session_lock;

END pkg_demo;
/
-- #endregion

-- #region run_reset
EXEC pkg_demo.reset_all;

