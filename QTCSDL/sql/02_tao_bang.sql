-- #region departments
CREATE TABLE departments (
  dept_id      NUMBER(6)
               GENERATED BY DEFAULT ON NULL AS IDENTITY,
  dept_code    VARCHAR2(20)       NOT NULL,
  dept_name    VARCHAR2(200 CHAR) NOT NULL,
  created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_departments PRIMARY KEY (dept_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT uq_departments_code UNIQUE (dept_code)
    USING INDEX TABLESPACE ts_hf_index
);
-- #endregion

-- #region users
CREATE TABLE users (
  user_id        NUMBER(10)
                 GENERATED BY DEFAULT ON NULL AS IDENTITY,
  username       VARCHAR2(30)       NOT NULL,
  full_name      VARCHAR2(100 CHAR) NOT NULL,
  email          VARCHAR2(150)      NOT NULL,
  password_hash  VARCHAR2(255)      NOT NULL,
  user_type      VARCHAR2(10)       NOT NULL,
  user_role      VARCHAR2(10) DEFAULT 'USER'   NOT NULL,
  dept_id        NUMBER(6),
  status         VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at     TIMESTAMP,
  last_login_at  TIMESTAMP,
  CONSTRAINT pk_users PRIMARY KEY (user_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT uq_users_username UNIQUE (username)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT uq_users_email UNIQUE (email)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT fk_users_dept FOREIGN KEY (dept_id)
    REFERENCES departments (dept_id),
  CONSTRAINT ck_users_email CHECK (
    email = LOWER(email)
    AND REGEXP_LIKE(email, '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$')),
  CONSTRAINT ck_users_type
    CHECK (user_type IN ('STUDENT', 'LECTURER', 'STAFF')),
  CONSTRAINT ck_users_role   CHECK (user_role IN ('USER', 'ADMIN')),
  CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'LOCKED'))
);
-- #endregion

-- #region forms
CREATE TABLE forms (
  form_id             NUMBER(10)
                      GENERATED BY DEFAULT ON NULL AS IDENTITY,
  owner_id            NUMBER(10)         NOT NULL,
  short_code          VARCHAR2(10)       NOT NULL,
  title               VARCHAR2(255 CHAR) NOT NULL,
  description         VARCHAR2(1000 CHAR),
  status              VARCHAR2(10) DEFAULT 'DRAFT' NOT NULL,
  is_anonymous        NUMBER(1)    DEFAULT 0 NOT NULL,
  require_login       NUMBER(1)    DEFAULT 1 NOT NULL,
  limit_one_response  NUMBER(1)    DEFAULT 0 NOT NULL,
  max_responses       NUMBER(6),
  response_count      NUMBER(10)   DEFAULT 0 NOT NULL,
  open_at             TIMESTAMP,
  close_at            TIMESTAMP,
  settings            CLOB,
  created_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at          TIMESTAMP,
  deleted_at          TIMESTAMP,
  CONSTRAINT pk_forms PRIMARY KEY (form_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT uq_forms_short_code UNIQUE (short_code)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT fk_forms_owner FOREIGN KEY (owner_id)
    REFERENCES users (user_id),
  CONSTRAINT ck_forms_code
    CHECK (REGEXP_LIKE(short_code, '^[A-Za-z0-9]{6,10}$')),
  CONSTRAINT ck_forms_status
    CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED')),
  CONSTRAINT ck_forms_flags CHECK (is_anonymous IN (0, 1)
    AND require_login IN (0, 1) AND limit_one_response IN (0, 1)),
  CONSTRAINT ck_forms_one_resp
    CHECK (limit_one_response = 0 OR require_login = 1),
  CONSTRAINT ck_forms_max
    CHECK (max_responses IS NULL OR max_responses > 0),
  CONSTRAINT ck_forms_quota CHECK (response_count >= 0
    AND (max_responses IS NULL OR response_count <= max_responses)),
  CONSTRAINT ck_forms_time
    CHECK (open_at IS NULL OR close_at IS NULL OR close_at > open_at),
  CONSTRAINT ck_forms_settings CHECK (settings IS JSON)
)
LOB (settings) STORE AS SECUREFILE (TABLESPACE ts_hf_data);
-- #endregion

-- #region form_collaborators
CREATE TABLE form_collaborators (
  form_id     NUMBER(10)   NOT NULL,
  user_id     NUMBER(10)   NOT NULL,
  permission  VARCHAR2(10) DEFAULT 'VIEWER' NOT NULL,
  added_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_form_collaborators PRIMARY KEY (form_id, user_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT fk_fc_form FOREIGN KEY (form_id)
    REFERENCES forms (form_id) ON DELETE CASCADE,
  CONSTRAINT fk_fc_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT ck_fc_permission
    CHECK (permission IN ('EDITOR', 'VIEWER'))
);
-- #endregion

-- #region questions
CREATE TABLE questions (
  question_id    NUMBER(12)
                 GENERATED BY DEFAULT ON NULL AS IDENTITY,
  form_id        NUMBER(10)         NOT NULL,
  sort_order     NUMBER(4)          NOT NULL,
  question_type  VARCHAR2(20)       NOT NULL,
  title          VARCHAR2(500 CHAR) NOT NULL,
  help_text      VARCHAR2(1000 CHAR),
  is_required    NUMBER(1) DEFAULT 0 NOT NULL,
  config         VARCHAR2(4000),
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_questions PRIMARY KEY (question_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT fk_questions_form FOREIGN KEY (form_id)
    REFERENCES forms (form_id) ON DELETE CASCADE,
  CONSTRAINT uq_questions_order UNIQUE (form_id, sort_order)
    DEFERRABLE INITIALLY DEFERRED
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT ck_questions_type CHECK (question_type IN (
    'SHORT_TEXT', 'PARAGRAPH', 'SINGLE_CHOICE', 'MULTI_CHOICE',
    'DROPDOWN', 'LINEAR_SCALE', 'NUMBER', 'DATE')),
  CONSTRAINT ck_questions_order    CHECK (sort_order > 0),
  CONSTRAINT ck_questions_required CHECK (is_required IN (0, 1)),
  CONSTRAINT ck_questions_config   CHECK (config IS JSON)
);
-- #endregion

-- #region question_options
CREATE TABLE question_options (
  option_id    NUMBER(12)
               GENERATED BY DEFAULT ON NULL AS IDENTITY,
  question_id  NUMBER(12)         NOT NULL,
  sort_order   NUMBER(4)          NOT NULL,
  label        VARCHAR2(500 CHAR) NOT NULL,
  CONSTRAINT pk_question_options PRIMARY KEY (option_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT fk_options_question FOREIGN KEY (question_id)
    REFERENCES questions (question_id) ON DELETE CASCADE,
  CONSTRAINT uq_options_order UNIQUE (question_id, sort_order)
    DEFERRABLE INITIALLY DEFERRED
    USING INDEX TABLESPACE ts_hf_index,
  -- Khóa dự tuyển phục vụ khóa ngoại kép từ bảng ANSWERS
  CONSTRAINT uq_options_question UNIQUE (question_id, option_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT ck_options_order CHECK (sort_order > 0)
);
-- #endregion

-- #region responses
CREATE TABLE responses (
  response_id    NUMBER(14)
                 GENERATED BY DEFAULT ON NULL AS IDENTITY,
  form_id        NUMBER(10) NOT NULL,
  respondent_id  NUMBER(10),
  once_key       NUMBER(10),
  submitted_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  duration_sec   NUMBER(6),
  ip_address     VARCHAR2(45),
  user_agent     VARCHAR2(500),
  CONSTRAINT pk_responses PRIMARY KEY (response_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT fk_responses_form FOREIGN KEY (form_id)
    REFERENCES forms (form_id),
  CONSTRAINT fk_responses_user FOREIGN KEY (respondent_id)
    REFERENCES users (user_id),
  CONSTRAINT ck_responses_once
    CHECK (once_key IS NULL OR once_key = respondent_id),
  CONSTRAINT ck_responses_duration
    CHECK (duration_sec IS NULL OR duration_sec >= 0)
)
TABLESPACE ts_hf_data
PARTITION BY RANGE (submitted_at)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
  PARTITION p_before_2026
    VALUES LESS THAN (TIMESTAMP '2026-01-01 00:00:00')
);
-- #endregion

-- #region answers
CREATE TABLE answers (
  answer_id      NUMBER(16)
                 GENERATED BY DEFAULT ON NULL AS IDENTITY,
  response_id    NUMBER(14) NOT NULL,
  question_id    NUMBER(12) NOT NULL,
  option_id      NUMBER(12),
  answer_text    VARCHAR2(2000 CHAR),
  answer_number  NUMBER,
  answer_date    DATE,
  CONSTRAINT pk_answers PRIMARY KEY (answer_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT fk_answers_response FOREIGN KEY (response_id)
    REFERENCES responses (response_id) ON DELETE CASCADE,
  CONSTRAINT fk_answers_question FOREIGN KEY (question_id)
    REFERENCES questions (question_id),
  -- Lựa chọn được ghi nhận phải thuộc đúng câu hỏi được trả lời
  CONSTRAINT fk_answers_option FOREIGN KEY (question_id, option_id)
    REFERENCES question_options (question_id, option_id),
  CONSTRAINT ck_answers_value CHECK (
    option_id IS NOT NULL OR answer_text IS NOT NULL
    OR answer_number IS NOT NULL OR answer_date IS NOT NULL)
)
PARTITION BY REFERENCE (fk_answers_response);
-- #endregion

-- #region audit_logs
CREATE TABLE audit_logs (
  log_id       NUMBER(16) GENERATED ALWAYS AS IDENTITY,
  table_name   VARCHAR2(30)  NOT NULL,
  operation    VARCHAR2(6)   NOT NULL,
  record_id    VARCHAR2(50)  NOT NULL,
  old_values   CLOB,
  new_values   CLOB,
  db_user      VARCHAR2(128)
               DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  app_user_id  NUMBER(10),
  client_ip    VARCHAR2(45)
               DEFAULT SYS_CONTEXT('USERENV', 'IP_ADDRESS'),
  action_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_audit_logs PRIMARY KEY (log_id)
    USING INDEX TABLESPACE ts_hf_index,
  CONSTRAINT ck_audit_operation
    CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
  CONSTRAINT ck_audit_old CHECK (old_values IS JSON),
  CONSTRAINT ck_audit_new CHECK (new_values IS JSON)
)
LOB (old_values, new_values) STORE AS SECUREFILE;
-- #endregion

