-- #region check_tables
-- Kiểm tra các bảng đã tạo: bảng phân vùng không gắn với một tablespace cố định
SELECT table_name,
       NVL(tablespace_name, '(theo phân vùng)') AS tablespace_name,
       partitioned
  FROM user_tables
 ORDER BY table_name;
-- #endregion
